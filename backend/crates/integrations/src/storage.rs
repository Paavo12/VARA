//! Object storage for identity images and driver documents.
//!
//! Clients never send files through the API's JSON endpoints: they receive a short-lived
//! signed URL and upload straight to storage (TRD §7.2). With the `Local` backend the "storage
//! service" is a directory on disk and the signed URLs point at `/v1/storage/...` on the API,
//! which checks the signature, expiry, content type and size exactly as S3 checks a
//! pre-signed request. On Google Cloud the bucket does all of this itself (`crate::gcs`).

use std::{
    io,
    path::{Path, PathBuf},
};

use base64::{Engine, engine::general_purpose::URL_SAFE_NO_PAD as B64};
use fuber_common::crypto::{Hasher, ct_eq};

use crate::gcs::{Endpoints, Gcs};

pub const MAX_UPLOAD_BYTES: u64 = 10 * 1024 * 1024;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PresignedUpload {
    pub method: &'static str,
    pub url: String,
    /// Headers the client must send unchanged.
    pub headers: Vec<(&'static str, String)>,
    pub expires_at: i64,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Op {
    Get,
    Put,
}

impl Op {
    fn as_str(self) -> &'static str {
        match self {
            Op::Get => "get",
            Op::Put => "put",
        }
    }
}

/// What a signed URL allows, recovered from its query string.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Grant {
    pub op: Op,
    pub key: String,
    pub content_type: String,
    pub max_bytes: u64,
    pub expires_at: i64,
}

pub enum ObjectStore {
    Local(LocalDisk),
    Gcs(Box<Gcs>),
}

impl ObjectStore {
    /// The store for this configuration. The API and the worker both build it this way, so
    /// they agree on where files live and how URLs are signed.
    pub fn from_config(config: &fuber_common::Config, hasher: Hasher) -> ObjectStore {
        match &config.storage {
            fuber_common::StorageConfig::Local { dir, public_url } => ObjectStore::Local(LocalDisk::new(dir.clone(), public_url, hasher)),
            fuber_common::StorageConfig::Gcs { bucket } => ObjectStore::Gcs(Box::new(Gcs::new(bucket, Endpoints::default()))),
        }
    }

    /// Signing with GCS asks Google, so it can fail.
    pub async fn presign_put(&self, key: &str, content_type: &str, max_bytes: u64, expires_at: i64) -> io::Result<PresignedUpload> {
        match self {
            ObjectStore::Local(l) => Ok(l.presign_put(key, content_type, max_bytes, expires_at)),
            ObjectStore::Gcs(g) => g.presign_put(key, content_type, max_bytes, expires_at).await,
        }
    }

    pub async fn presign_get(&self, key: &str, expires_at: i64) -> io::Result<String> {
        match self {
            ObjectStore::Local(l) => Ok(l.presign_get(key, expires_at)),
            ObjectStore::Gcs(g) => g.presign_get(key, expires_at).await,
        }
    }

    pub async fn read(&self, key: &str) -> io::Result<Vec<u8>> {
        match self {
            ObjectStore::Local(l) => tokio::fs::read(l.path(key)?).await,
            ObjectStore::Gcs(g) => g.read(key).await,
        }
    }

    pub async fn write(&self, key: &str, bytes: &[u8]) -> io::Result<()> {
        match self {
            ObjectStore::Local(l) => l.write(key, bytes).await,
            ObjectStore::Gcs(g) => g.write(key, bytes).await,
        }
    }

    /// Deleting a missing object is not an error.
    pub async fn delete(&self, key: &str) -> io::Result<()> {
        match self {
            ObjectStore::Local(l) => match tokio::fs::remove_file(l.path(key)?).await {
                Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(()),
                r => r,
            },
            ObjectStore::Gcs(g) => g.delete(key).await,
        }
    }

    pub fn local(&self) -> Option<&LocalDisk> {
        match self {
            ObjectStore::Local(l) => Some(l),
            ObjectStore::Gcs(_) => None,
        }
    }
}

/// Object keys are generated by the server (`quarantine/<uuid>`, `clean/<uuid>/<uuid>.jpg`),
/// never taken from users; this check is defence in depth against path traversal.
pub fn valid_key(key: &str) -> bool {
    !key.is_empty()
        && key.len() <= 200
        && !key.starts_with('/')
        && key.split('/').all(|seg| !seg.is_empty() && seg != "." && seg != "..")
        && key.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b"-_./".contains(&b))
}

pub struct LocalDisk {
    dir: PathBuf,
    public_url: String,
    hasher: Hasher,
}

impl LocalDisk {
    /// `hasher` signs URLs; pass the API's keyed hasher.
    pub fn new(dir: impl Into<PathBuf>, public_url: &str, hasher: Hasher) -> Self {
        LocalDisk { dir: dir.into(), public_url: public_url.trim_end_matches('/').to_owned(), hasher }
    }

    pub fn dir(&self) -> &Path {
        &self.dir
    }

    fn path(&self, key: &str) -> io::Result<PathBuf> {
        if !valid_key(key) {
            return Err(io::Error::new(io::ErrorKind::InvalidInput, "invalid object key"));
        }
        Ok(self.dir.join(key))
    }

    async fn write(&self, key: &str, bytes: &[u8]) -> io::Result<()> {
        let path = self.path(key)?;
        if let Some(parent) = path.parent() {
            tokio::fs::create_dir_all(parent).await?;
        }
        // Write then rename, so a reader never sees half a file.
        let tmp = path.with_extension(format!("part-{}", B64.encode(fuber_common::crypto::random_bytes::<6>())));
        tokio::fs::write(&tmp, bytes).await?;
        tokio::fs::rename(&tmp, &path).await
    }

    fn signature(&self, g: &Grant) -> String {
        let msg = format!("{}\0{}\0{}\0{}\0{}", g.op.as_str(), g.key, g.content_type, g.max_bytes, g.expires_at);
        B64.encode(self.hasher.hash("storage-url", msg.as_bytes()))
    }

    fn url(&self, g: &Grant) -> String {
        format!(
            "{}/v1/storage/{}?op={}&exp={}&max={}&sig={}",
            self.public_url,
            g.key,
            g.op.as_str(),
            g.expires_at,
            g.max_bytes,
            self.signature(g)
        )
    }

    pub fn presign_put(&self, key: &str, content_type: &str, max_bytes: u64, expires_at: i64) -> PresignedUpload {
        let g = Grant { op: Op::Put, key: key.to_owned(), content_type: content_type.to_owned(), max_bytes, expires_at };
        PresignedUpload { method: "PUT", url: self.url(&g), headers: vec![("content-type", content_type.to_owned())], expires_at }
    }

    pub fn presign_get(&self, key: &str, expires_at: i64) -> String {
        self.url(&Grant { op: Op::Get, key: key.to_owned(), content_type: String::new(), max_bytes: 0, expires_at })
    }

    /// Checks a request against its signed URL. `content_type` is the request's header for
    /// uploads and ignored for downloads.
    #[allow(clippy::too_many_arguments)]
    pub fn verify(&self, op: Op, key: &str, content_type: &str, max_bytes: u64, expires_at: i64, sig: &str, now: i64) -> Option<Grant> {
        if now >= expires_at || !valid_key(key) {
            return None;
        }
        let ct = if op == Op::Put { content_type } else { "" };
        let mb = if op == Op::Put { max_bytes } else { 0 };
        let g = Grant { op, key: key.to_owned(), content_type: ct.to_owned(), max_bytes: mb, expires_at };
        ct_eq(self.signature(&g).as_bytes(), sig.as_bytes()).then_some(g)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn disk() -> LocalDisk {
        let hasher = Hasher::new(&"storage-test-0123456789abcdef0123456".to_owned().into());
        LocalDisk::new(std::env::temp_dir().join("fuber-storage-test"), "http://127.0.0.1:8080/", hasher)
    }

    fn query(url: &str, name: &str) -> String {
        url.split(['?', '&']).find_map(|p| p.strip_prefix(&format!("{name}="))).unwrap().to_owned()
    }

    #[test]
    fn keys_cannot_escape_the_root() {
        assert!(valid_key("quarantine/0b8e2f9c-2a5e-4a4b-9a49-8d1f1f2f3a4b"));
        assert!(valid_key("clean/a/b.jpg"));
        for bad in ["", "/etc/passwd", "../x", "a/../b", "a//b", "A/B", "a\\b", "a/./b", "a b"] {
            assert!(!valid_key(bad), "{bad:?}");
        }
    }

    #[test]
    fn signed_put_url_round_trips_and_binds_every_field() {
        let d = disk();
        let p = d.presign_put("quarantine/abc", "image/jpeg", 1000, 2_000);
        assert!(p.url.starts_with("http://127.0.0.1:8080/v1/storage/quarantine/abc?op=put"));
        let sig = query(&p.url, "sig");
        assert!(d.verify(Op::Put, "quarantine/abc", "image/jpeg", 1000, 2_000, &sig, 1_999).is_some());
        assert!(d.verify(Op::Put, "quarantine/abc", "image/jpeg", 1000, 2_000, &sig, 2_000).is_none(), "expired");
        assert!(d.verify(Op::Put, "quarantine/abd", "image/jpeg", 1000, 2_000, &sig, 0).is_none(), "other key");
        assert!(d.verify(Op::Put, "quarantine/abc", "text/html", 1000, 2_000, &sig, 0).is_none(), "other type");
        assert!(d.verify(Op::Put, "quarantine/abc", "image/jpeg", 9999, 2_000, &sig, 0).is_none(), "bigger size");
        assert!(d.verify(Op::Put, "quarantine/abc", "image/jpeg", 1000, 9_999, &sig, 0).is_none(), "longer expiry");
        assert!(d.verify(Op::Get, "quarantine/abc", "", 0, 2_000, &sig, 0).is_none(), "upload URL cannot download");
    }

    #[tokio::test]
    async fn write_read_delete() {
        let s = ObjectStore::Local(disk());
        s.write("test/obj", b"hello").await.unwrap();
        assert_eq!(s.read("test/obj").await.unwrap(), b"hello");
        s.delete("test/obj").await.unwrap();
        s.delete("test/obj").await.unwrap();
        assert!(s.read("test/obj").await.is_err());
        assert!(s.write("../escape", b"x").await.is_err());
    }
}
