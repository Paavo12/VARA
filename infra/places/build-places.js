#!/usr/bin/env node
/*
 * Builds backend/migrations/0006_seed_places.sql from the demo's Windhoek data, so search in
 * the real apps finds exactly what the demo finds: its landmarks, suburb centres and one point
 * per named street (the middle of the street's longest stretch, snapped to the road).
 *
 *   node infra/places/build-places.js
 *
 * The street data is OpenStreetMap (© OpenStreetMap contributors, ODbL), built into the demo
 * by demo/tools/build-roads.js. Re-run this after rebuilding the demo's roads.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const E = require('../../demo/public/js/engine.js');

const sql = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const coord = (p) => {
  const { lat, lon } = E.toLatLng(p);
  return { lat: +lat.toFixed(6), lon: +lon.toFixed(6) };
};

const rows = [];
const seen = new Set();
function add(kind, name, detail, p, rank, keywords = '') {
  const key = kind + '|' + name;
  if (seen.has(key)) return;
  seen.add(key);
  const { lat, lon } = coord(p);
  rows.push(`  (${sql(kind)}, ${sql(name)}, ${sql(detail)}, ${sql(keywords)}, ${lon}, ${lat}, ${rank})`);
}

for (const pl of E.PLACES) add('landmark', pl.name, pl.kind + ' · ' + E.addressOf(E.snap(pl)), E.snap(pl), 0, pl.kind);
for (const z of E.SUBURBS) add('suburb', z.name, 'Suburb of Windhoek', E.snap(z), 1);
for (const name of [...new Set(E.ROADS.names)].sort()) {
  // Road refs such as "B6" are not names people search for.
  if (/^[A-Z]\d+$/.test(name)) continue;
  const hit = E.searchPlaces(name, 50).find((r) => r.type === 'street' && r.name === name);
  if (hit) add('street', name, 'Street · ' + E.zoneOf(hit), hit, 2);
}

const out = [
  '-- Generated by infra/places/build-places.js — do not edit by hand.',
  '-- Windhoek landmarks, suburbs and streets from the demo (OpenStreetMap data © OpenStreetMap',
  '-- contributors, ODbL). Search matches the demo: case, accents and punctuation are ignored.',
  '',
  'INSERT INTO places (kind, name, detail, keywords, location, rank) SELECT kind::place_kind, name, detail, keywords, ST_SetSRID(ST_MakePoint(lon, lat), 4326)::geography, rank FROM (VALUES',
  rows.join(',\n'),
  ') AS v (kind, name, detail, keywords, lon, lat, rank);',
  '',
].join('\n');
const file = path.join(__dirname, '../../backend/migrations/0006_seed_places.sql');
fs.writeFileSync(file, out);
console.log(`${rows.length} places → ${path.relative(process.cwd(), file)}`);
